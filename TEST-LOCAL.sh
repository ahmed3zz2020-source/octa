#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════
# 🧪 تشغيل محلي — من غير ما تلمس الدومين
# ══════════════════════════════════════════════════════════════
#
# الفكرة: بتشوف تعديلاتك على جهازك بس.
# الدومين بيفضل زي ما هو.
# لما تبقى مرتاح → deploy.
#
# ══════════════════════════════════════════════════════════════

set -e

ROOT="$(cd "$(dirname "$0")" && pwd)"
PORT="${1:-8080}"

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║  🧪 OCTA — وضع التجربة                        ║"
echo "╚══════════════════════════════════════════════╝"
echo ""
echo "  📂 المصدر   : $ROOT"
echo "  🌐 محلي     : http://localhost:$PORT"
echo "  🚫 الدومين  : مش هيتلمس خالص"
echo ""
echo "  ⚠️ البوابة بتتفتحش على localhost"
echo "     (ده مقصود — عشان تتجرب بحرية)"
echo ""
echo "  📋 للتجربة على الموبايل في نفس الشبكة:"
echo "     http://$(hostname -I 2>/dev/null | awk '{print $1}'):$PORT"
echo ""
echo "  ⏹️ للإيقاف: Ctrl+C"
echo "  ─────────────────────────────────────────"
echo ""

# بنسخ للـdist لو مش موجود (عشان يبقى فيه favicon و JSON)
if [ ! -f "$ROOT/dist/index.html" ]; then
  echo "  📦 أول تشغيل — بنجهّز الملفات…"
  cd "$ROOT" && npm run build >/dev/null 2>&1
  echo "  ✅ جاهز"
  echo ""
fi

cd "$ROOT/dist"
exec python3 -m http.server "$PORT" --bind 0.0.0.0