/* ════════════════════════════════════════════════════════════════
 * 🛡️ الأوزان الحيّة للمحاور (مصدر واحد — مش نسخ مكتوبة)
 * ────────────────────────────────────────────────────────────────
 * ⛔⛔⛔ ٢٧ أكتوبر ٢٠٢٦ — الأوزان كانت مكتوبة **بالحرف** في ٤ صفحات
 * ⛌   (الأذرع · الشات/السكنر ×2 · كارت القرار) ⇒ أول ما الباك غيّر
 * ⛌   الأوزان (٢٦ أكتوبر: شيل محور المحفظة ٩٪ وتوزيعه) ⇒ الموقع
 * ⛌   فضل يعرض «المحفظة ٩٪ ثابت» و«١٤٪ من الوزن ثابت» = معلومة غلط.
 * 📌 القاعدة: أي رقم عن المحرك يقرأ من المصدر الحيّ (/api/engine-weights).
 * 📌 والبديل (FALLBACK) = الأوزان الصح الحالية، مش القديمة.
 * ════════════════════════════════════════════════════════════════ */
window.OCTA_AXIS_W = function () {
  var FALLBACK = { technical: 20, fundamental: 24, liquidity: 20, news: 5, sentiment: 4, risk: 27, portfolio: 0 };
  var src = (window.CFG && window.CFG.engineWeights) || {};
  var out = {};
  Object.keys(FALLBACK).forEach(function (k) {
    var v = Number(src[k]);
    if (!isFinite(v)) v = FALLBACK[k];
    if (v > 0 && v <= 1) v = v * 100;   /* لو الأوزان كسور (0.24) ⇒ 24% */
    out[k] = Math.round(v * 10) / 10;
  });
  return out;
};

/* ══════════════════════════════════════════════════════════════
  ⚖️ تحميل الأوزان من السيرفر (محمي)
  ──────────────────────────────────────────────────────────────
  ⛔⛔⛔ ٢٠ أكتوبر ٢٠٢٦
  ⛌ الأوزان كانت مكتوبة في هذا الملف — كان أي حد يقدر يقراها.
  ⛌ دلوقتي: /api/engine-weights محمي بـrequire_user،
  ⛌ وبنملا CFG.weights و CFG.engineWeights بعد الدخول.
  ⛌ فـ«ارفع على الدومين» مش لازم يتغيّر — الأوزان جاية من السيرفر.
  ══════════════════════════════════════════════════════════════ */
(function () {
  if (typeof window === 'undefined') return;
  var CFG = window.CFG;
  if (!CFG) return;

  /* ⛔⛔⛔ ٢٦ أكتوبر ٢٠٢٦ — ⭐ منع تكرار نفس الطلب
  📌 الكود كان بيعمل ٦ نداءات /api/engine-weights (DOMContentLoaded
  📌 + ٥٠٠ + ٢٥٠٠ + ٦٠٠٠ + الحدث + الـinterval) ⇒ كل نداء كان
  📌 ⛌⛌⛌ بيلفّي «octa:weights» ⇒ إعادة رسم كارت القرار ⇒ ٣ نداءات
  📌 ⛌⛌⛌ غالية × ٦ = ١٨ ⇒ فوق حد الـrate limit ⇒ 429 للمستخدم.
  📌 ✅ الحل: نطلب مرة واحدة، ونتجاهل لو الحد اتخزّن أصلاً. */
  var _req = false, _got = false;

  function apply(d) {
    if (!d || !d.ok) return;
    var _hasEngine = !!(d.engine && Object.keys(d.engine).length);
    if (_hasEngine) {
      CFG.engineWeights = d.engine;
      /* ⭐⭐⭐ ٢٥ أكتوبر ٢٠٢٦ — ⭐ السيرفر بيبعت الأوزان في d.engine
      📌 السبب: CFG.weights.egx / .intel كانوا فاضيين ⇒ كل الأوزان «0%».
      📌 ✅ الحل: ننسخ نفس الأوزان لكل أسواق (مصدر واحد — الباك). */
      ['us','egx','usScan','intel'].forEach(function (k) {
        if (!CFG.weights[k] || !Object.keys(CFG.weights[k]).length) CFG.weights[k] = d.engine;
      });
    }
    if (d.weights) {
      ['us','egx','usScan','intel'].forEach(function (k) {
        if (d.weights[k] && Object.keys(d.weights[k]).length) CFG.weights[k] = d.weights[k];
      });
    }
    /* 🎯 إعادة الرسم: الصفحات اللي اتحسبت بأوزان فاضية
       لازم تتحدّث بعد ما الأوزان توصل.
       ⛔⛔⛔ ٢٦ أكتوبر ٢٠٢٦ — ⭐ بس **مرة واحدة**!
       📌 كل نداء لـload() كان بيعمل dispatch ⇒ إعادة رسم مكرّرة
       📌 ⛌⛌⛌ ⇒ نداءات مكرّرة للـAPI الغالية ⇒ 429. */
    try { if (typeof window.octaWeightsReady === 'function') window.octaWeightsReady(); }
    catch (e) { }
    if (_got || !_hasEngine) return;  /* ⛔ الأوزان وصلت قبل كده ⇒ متكرّرش */
    _got = true;
    document.dispatchEvent(new CustomEvent('octa:weights'));
  }

  /* ⛔ بنجيبها مرتين: مرة عند.authed ومرة احتياطاً.
  ⛌ لو البوابة أسرع من تحميل السكربت، الـauthed ممكن يفوتنا. */
  function load() {
    if (window.OCTA_API === undefined) return;
    if (_req) return;        /* ⛔⛔⛔ طلب جاري ⇒ متكرّرش (٦ نداءات → ١) */
    _req = true;
    try {
      /* ════════════════════════════════════════════════════════════════
      ⭐⭐⭐ ٢٥ أكتوبر ٢٠٢٦ — ⭐ إرسال التوكن مع طلب الأوزان
      ────────────────────────────────────────────────────────────────
      📌 المشكلة: الطلب كان **من غير Authorization** ⇒ 401 ⇒
      📌 ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌
      📌 ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌
      📌 ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌ ⛌
      📌 ⛌ ⛌ ⇒ الأوزان فضل فاضية ⇒ «أوزان المحرك» مش بتظهر.
      📌 ✅ الحل: نبعت الـBearer من localStorage + credentials.
      ════════════════════════════════════════════════════════════════ */
      var _h = { 'Accept': 'application/json' };
      try {
        var _tok = localStorage.getItem('octa_token') || '';
        if (_tok) _h['Authorization'] = 'Bearer ' + _tok;
      } catch (e) { }
      fetch(window.OCTA_API + '/api/engine-weights', {
        cache: 'no-store',
        headers: _h,
        credentials: 'include'
      })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(apply).catch(function () { })
      .then(function () { _req = false; });   /* ⛔ نسمح بمحاولة تانية بعد الفشل */
    } catch (e) { _req = false; }
  }

  document.addEventListener('octa:authed', function () { setTimeout(load, 60); });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { setTimeout(load, 900); });
  else setTimeout(load, 500);
  /* ⭐ إعادة محاولة: لو التوكن لسه مش متخزن وقت الطلب الأول */
  setTimeout(load, 2500);
  setTimeout(load, 6000);
  /* ⭐ ونشوف لو localStorage اتغيّر (البوابة حفظت توكن) */
  try {
    var _lastTok = '';
    setInterval(function () {
      try {
        var _t = localStorage.getItem('octa_token') || '';
        if (_t && _t !== _lastTok) { _lastTok = _t; load(); }
      } catch (e) { }
    }, 2000);
  } catch (e) { }
})();
